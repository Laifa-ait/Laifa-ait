export async function ensureInitialSeedProperties(firestore: FirebaseFirestore.Firestore) {
  try {
    const snap = await firestore.collection('real_estate_properties').limit(1).get();
    if (snap.empty) {
      safeLogger.info('Seeding initial Olma Immo properties into Firestore');
      const batch = firestore.batch();
      for (const p of SEED_REAL_ESTATE_PROPERTIES) {
        const ref = firestore.collection('real_estate_properties').doc(p.id);
        batch.set(ref, p);
      }
      await batch.commit();
      safeLogger.info('Initial Olma Immo properties seeded successfully');
    }
  } catch (err) {
    safeLogger.error('Error seeding initial Olma Immo properties', { err: err instanceof Error ? err.message : String(err) });
  }
}

export function toPropertyMapResult(p: Property & { distanceKm?: number }): PropertyMapResult {
  return {
    id: p.id,
    title: p.title,
    propertyType: p.propertyType,
    listingType: p.listingType,
    legalPapers: p.legalPapers,
    isLegalVerified: p.isLegalVerified,
    legalPaperType: p.legalPaperType,
    price: p.price,
    pricePeriod: p.pricePeriod,
    lat: p.location.lat,
    lng: p.location.lng,
    commune: p.location.commune,
    wilaya: p.location.wilaya,
    mainImage: p.images && p.images.length > 0 ? p.images[0] : '',
    rooms: p.rooms,
    areaSquareMeters: p.areaSquareMeters,
    distanceKm: p.distanceKm,
  };
}
