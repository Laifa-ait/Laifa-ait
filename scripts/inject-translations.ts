function updateLang(lang: string, additions: Record<string, string>) {
  const publicPath = path.join(process.cwd(), "public", "locales", `${lang}.json`);
  const distPath = path.join(process.cwd(), "dist", "locales", `${lang}.json`);

  let current: Record<string, string> = {};
  if (fs.existsSync(publicPath)) {
    current = JSON.parse(fs.readFileSync(publicPath, "utf-8"));
  }

  let count = 0;
  for (const [k, v] of Object.entries(additions)) {
    if (!current[k]) {
      current[k] = v;
      count++;
    }
  }

  fs.writeFileSync(publicPath, JSON.stringify(current, null, 2) + "\n", "utf-8");
  if (fs.existsSync(path.dirname(distPath))) {
    fs.writeFileSync(distPath, JSON.stringify(current, null, 2) + "\n", "utf-8");
  }
  console.log(`Updated ${lang}.json: added ${count} new keys. Total keys: ${Object.keys(current).length}`);
}

